package com.firstfood.payment;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.Objects;
import java.util.UUID;

/**
 * One payment a customer reports against one subscription. What the customer submitted never changes; staff only
 * decide it, once (PENDING -> VERIFIED or REJECTED; V17 enforces both). The customer's date and time are claims,
 * kept apart from {@code submittedAt}, which the server stamps.
 */
@Entity
@Table(name = "subscription_payment")
public class SubscriptionPayment {

    @Id
    private UUID id;

    @Column(name = "subscription_id", nullable = false, updatable = false)
    private UUID subscriptionId;

    @Column(name = "provider_id", nullable = false, updatable = false)
    private UUID providerId;

    @Column(name = "customer_account_id", nullable = false, updatable = false)
    private UUID customerAccountId;

    @Column(name = "subscriber_name_snapshot", nullable = false, updatable = false, length = 150)
    private String subscriberNameSnapshot;

    @Column(name = "transaction_reference", updatable = false, length = 150)
    private String transactionReference;

    /** Generated by the database (V22): the reference without spaces/separators, upper-case. Never written by JPA. */
    @Column(name = "reference_key", insertable = false, updatable = false, length = 150)
    private String referenceKey;

    @Column(nullable = false, updatable = false, precision = 12, scale = 2)
    private BigDecimal amount;

    @Column(nullable = false, updatable = false, length = 3)
    private String currency;

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_method", nullable = false, updatable = false, length = 20)
    private PaymentMethod paymentMethod;

    @Column(name = "customer_payment_date", nullable = false, updatable = false)
    private LocalDate customerPaymentDate;

    @Column(name = "customer_payment_time", nullable = false, updatable = false)
    private LocalTime customerPaymentTime;

    @Enumerated(EnumType.STRING)
    @Column(name = "verification_status", nullable = false, length = 20)
    private PaymentVerificationStatus verificationStatus = PaymentVerificationStatus.PENDING;

    @Column(name = "submitted_at", nullable = false, updatable = false)
    private Instant submittedAt;

    @Column(name = "verified_by_account_id")
    private UUID verifiedByAccountId;

    @Column(name = "verified_at")
    private Instant verifiedAt;

    @Column(name = "rejection_reason", length = 500)
    private String rejectionReason;

    @Column(name = "idempotency_key", updatable = false, length = 64)
    private String idempotencyKey;

    protected SubscriptionPayment() {
        // JPA
    }

    public SubscriptionPayment(UUID subscriptionId, UUID providerId, UUID customerAccountId,
            String subscriberNameSnapshot, String transactionReference, BigDecimal amount, String currency,
            PaymentMethod paymentMethod, LocalDate customerPaymentDate, LocalTime customerPaymentTime,
            Instant submittedAt, String idempotencyKey) {
        this.id = UUID.randomUUID();
        this.subscriptionId = Objects.requireNonNull(subscriptionId, "subscriptionId");
        this.providerId = Objects.requireNonNull(providerId, "providerId");
        this.customerAccountId = Objects.requireNonNull(customerAccountId, "customerAccountId");
        this.subscriberNameSnapshot = Objects.requireNonNull(subscriberNameSnapshot, "subscriberNameSnapshot");
        this.transactionReference = transactionReference;
        this.amount = Objects.requireNonNull(amount, "amount");
        this.currency = Objects.requireNonNull(currency, "currency");
        this.paymentMethod = Objects.requireNonNull(paymentMethod, "paymentMethod");
        this.customerPaymentDate = Objects.requireNonNull(customerPaymentDate, "customerPaymentDate");
        this.customerPaymentTime = Objects.requireNonNull(customerPaymentTime, "customerPaymentTime");
        this.submittedAt = Objects.requireNonNull(submittedAt, "submittedAt");
        this.idempotencyKey = idempotencyKey;
    }

    /** PENDING -> VERIFIED. Callers must have authorized the actor. */
    void verify(UUID byAccountId, Instant at) {
        requirePending();
        this.verificationStatus = PaymentVerificationStatus.VERIFIED;
        this.verifiedByAccountId = Objects.requireNonNull(byAccountId, "byAccountId");
        this.verifiedAt = Objects.requireNonNull(at, "at");
    }

    /** PENDING -> REJECTED, with the reason the customer will be shown. */
    void reject(UUID byAccountId, String reason, Instant at) {
        requirePending();
        if (reason == null || reason.isBlank()) {
            throw new IllegalArgumentException("A rejection needs a reason");
        }
        this.verificationStatus = PaymentVerificationStatus.REJECTED;
        this.verifiedByAccountId = Objects.requireNonNull(byAccountId, "byAccountId");
        this.verifiedAt = Objects.requireNonNull(at, "at");
        this.rejectionReason = reason;
    }

    boolean isPending() {
        return verificationStatus == PaymentVerificationStatus.PENDING;
    }

    private void requirePending() {
        if (!isPending()) {
            throw new IllegalStateException("Payment is " + verificationStatus + " and can no longer change");
        }
    }

    public UUID getId() {
        return id;
    }

    public UUID getSubscriptionId() {
        return subscriptionId;
    }

    public UUID getProviderId() {
        return providerId;
    }

    public UUID getCustomerAccountId() {
        return customerAccountId;
    }

    public String getSubscriberNameSnapshot() {
        return subscriberNameSnapshot;
    }

    public String getTransactionReference() {
        return transactionReference;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public String getCurrency() {
        return currency;
    }

    public PaymentMethod getPaymentMethod() {
        return paymentMethod;
    }

    public LocalDate getCustomerPaymentDate() {
        return customerPaymentDate;
    }

    public LocalTime getCustomerPaymentTime() {
        return customerPaymentTime;
    }

    public PaymentVerificationStatus getVerificationStatus() {
        return verificationStatus;
    }

    public Instant getSubmittedAt() {
        return submittedAt;
    }

    public UUID getVerifiedByAccountId() {
        return verifiedByAccountId;
    }

    public Instant getVerifiedAt() {
        return verifiedAt;
    }

    public String getRejectionReason() {
        return rejectionReason;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }
}
